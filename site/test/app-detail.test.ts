import { before, describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { execSync } from 'node:child_process';
import * as fs from 'node:fs';
import * as path from 'node:path';

describe('App Detail HTML Output Tests', () => {
  const siteRoot = path.resolve(import.meta.dirname, '..');
  const distDir = path.resolve(siteRoot, 'dist');
  const adobeHtmlPath = path.join(distDir, 'apps/adobe-scan/index.html');

  before(() => {
    if (!fs.existsSync(adobeHtmlPath)) {
      execSync('bun run build', { cwd: siteRoot, stdio: 'pipe' });
    }
  });

  it('renders app detail page with correct breadcrumb padding and profile alignment', () => {
    assert.ok(
      fs.existsSync(adobeHtmlPath),
      'Adobe Scan HTML must be generated by SSG',
    );

    const html = fs.readFileSync(adobeHtmlPath, 'utf-8');

    // Breadcrumb has px-4 sm:px-6
    assert.ok(
      html.includes('px-4 py-4 font-mono text-[10px] text-zinc-600 sm:px-6'),
      'Breadcrumb must use px-4 sm:px-6 padding',
    );

    // Hero eyebrow category is removed
    assert.ok(
      !html.includes('data-hero-category'),
      'Category eyebrow must be removed from AppDetailHero',
    );

    // About card category badge is removed
    assert.ok(
      !html.includes('data-panel-category'),
      'Category badge must be removed from About card',
    );

    // Target build row in What's new is removed
    assert.ok(
      !html.includes('<span>Target build</span>'),
      "Detached Target build row must be removed from What's new panel",
    );

    // Screenshots rail is present
    assert.ok(
      html.includes('data-screenshots-section'),
      'ScreenshotRail component must be present in markup',
    );

    // Reviews section is present
    assert.ok(
      html.includes('data-reviews-section'),
      'FeaturedReviews component must be present in markup',
    );

    // About dialog is present
    assert.ok(
      html.includes('id="about-app-dialog"'),
      'AboutAppDialog component must be present in markup',
    );

    // Show more button is present
    assert.ok(
      html.includes('data-trigger-about-dialog'),
      'Show more button must be present in markup',
    );
  });
});
