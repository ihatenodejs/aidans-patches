import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import type {
  App,
  AppTarget,
  ApkFileType,
  Patch,
  PatchOption,
  OptionType,
  RepositoryStats,
  ReleaseInfo,
  RawBundle,
  AppVersionStatus,
} from './types';
import { getPatchSourceUrl } from './source-links';
import { resolveLatestRelease, resolveLatestReleaseSync } from './changelog';
import { resolveAppForScope } from './commit-apps';

function slugify(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^\w\s-]/g, '')
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-+|-+$/g, '');
}

interface RawOption {
  key: string;
  title: string;
  description: string;
  required: boolean;
  type: string;
  default: string | boolean | number | null;
  values?: string[] | null;
}

interface RawTarget {
  version: string;
  versionCodes?: Record<string, number> | null;
  isExperimental: boolean;
  minSdk?: number | null;
  description?: string | null;
}

interface RawCompatiblePackage {
  packageName: string;
  name: string;
  description?: string | null;
  apkFileType?: string | null;
  appIconColor?: string | null;
  signatures?: string[] | null;
  targets: RawTarget[];
}

interface RawPatch {
  name: string;
  description: string;
  default: boolean;
  category?: string | null;
  dependencies: string[];
  compatiblePackages?: RawCompatiblePackage[] | null;
  options: RawOption[];
}

interface RawApp {
  packageName: string;
  name: string;
  description?: string | null;
  apkFileType: string;
  appIconColor?: string | null;
  signatures: string[];
  targets: RawTarget[];
  patchNames: string[];
  supportedVersions: string[];
  latestSupportedVersion: string;
}

interface RawPatchesList {
  version: string;
  apps: RawApp[];
  patches: RawPatch[];
}

let cachedData: {
  apps: App[];
  patches: Patch[];
  stats: RepositoryStats;
  release: ReleaseInfo;
  versionStatuses: AppVersionStatus[];
} | null = null;

interface RepositoryEntities {
  apps: App[];
  patches: Patch[];
  versionStatuses: AppVersionStatus[];
}

function buildRepositoryEntities(rawList: RawPatchesList) {
  if (!rawList.apps || !Array.isArray(rawList.apps)) {
    throw new Error('Invalid patches list data: missing "apps" array');
  }

  const appsById: Record<string, App> = {};
  const appsByPackage = new Map<string, App>();

  for (const rawApp of rawList.apps) {
    const appId = slugify(rawApp.name || rawApp.packageName);

    if (appsById[appId]) {
      throw new Error(
        `Slug conflict: "${appId}" generated by both ${appsById[appId].packageName} and ${rawApp.packageName}`,
      );
    }

    const appTargets: AppTarget[] = (rawApp.targets || []).map((t) => ({
      version: t.version,
      versionCodes: t.versionCodes,
      isExperimental: Boolean(t.isExperimental),
      minSdk: t.minSdk ?? null,
      description: t.description,
    }));

    const minSdk = appTargets.reduce<number | null>((acc, cur) => {
      if (cur.minSdk === null || cur.minSdk === undefined) return acc;
      return acc === null ? cur.minSdk : Math.min(acc, cur.minSdk);
    }, null);

    const docsName = appId === 'adobe-scan' ? 'adobe-scan' : appId;
    const docsUrl = `https://github.com/ihatenodejs/aidans-patches/tree/main/docs/${docsName}`;

    const app: App = {
      id: appId,
      name: rawApp.name,
      packageName: rawApp.packageName,
      apkFileType: (rawApp.apkFileType as ApkFileType) || 'APK',
      appIconColor: rawApp.appIconColor || '#3b82f6',
      targets: appTargets,
      supportedVersions: [...rawApp.supportedVersions],
      latestSupportedVersion: rawApp.latestSupportedVersion || 'Unknown',
      minSdk,
      signatures:
        rawApp.signatures && rawApp.signatures.length > 0
          ? [...rawApp.signatures]
          : null,
      patchCount: rawApp.patchNames ? rawApp.patchNames.length : 0,
      playStoreUrl: `https://play.google.com/store/apps/details?id=${encodeURIComponent(rawApp.packageName)}`,
      docsUrl,
    };

    appsById[appId] = app;
    appsByPackage.set(rawApp.packageName, app);
  }

  const patches: Patch[] = [];

  for (const rawPatch of rawList.patches) {
    const patchId = slugify(rawPatch.name);
    const options: PatchOption[] = (rawPatch.options || []).map((opt) => {
      let optType: OptionType = 'string';
      if (opt.type === 'kotlin.Boolean') {
        optType = 'boolean';
      } else if (
        opt.type === 'kotlin.String' &&
        typeof opt.default === 'string' &&
        opt.default.startsWith('#')
      ) {
        optType = 'color';
      }

      return {
        key: opt.key,
        title: opt.title,
        description: opt.description,
        required: Boolean(opt.required),
        type: optType,
        default: opt.default ?? '',
        values: Array.isArray(opt.values) ? opt.values : null,
      };
    });

    const compatibleAppIds: string[] = [];
    const compatiblePackages: Patch['compatiblePackages'] = [];

    if (rawPatch.compatiblePackages && rawPatch.compatiblePackages.length > 0) {
      for (const cp of rawPatch.compatiblePackages) {
        const app = appsByPackage.get(cp.packageName);
        if (!app) {
          throw new Error(
            `Patch "${rawPatch.name}" references absent app package "${cp.packageName}"`,
          );
        }
        compatibleAppIds.push(app.id);
        compatiblePackages.push({
          packageName: cp.packageName,
          name: cp.name,
          appIconColor: cp.appIconColor,
          apkFileType: cp.apkFileType,
        });
      }
    }

    patches.push({
      id: patchId,
      name: rawPatch.name,
      description: rawPatch.description,
      default: Boolean(rawPatch.default),
      category: rawPatch.category || null,
      dependencies: rawPatch.dependencies || [],
      compatibleAppIds,
      compatiblePackages,
      options,
      sourceUrl: getPatchSourceUrl(rawPatch.name, compatibleAppIds[0]),
    });
  }
  const apps = Object.values(appsById).sort((a, b) =>
    a.name.localeCompare(b.name),
  );

  const versionStatuses: AppVersionStatus[] = apps.map((app) => ({
    packageName: app.packageName,
    appName: app.name,
    appId: app.id,
    appIconColor: app.appIconColor,
    supportedVersions: app.supportedVersions,
    latestSupportedVersion: app.latestSupportedVersion,
    playVersion: null,
    checkedAt: null,
    updatedAt: null,
    updatedOn: null,
    status: 'unknown',
    playStoreUrl: app.playStoreUrl,
  }));

  return { apps, patches, versionStatuses };
}

function readLocalFiles() {
  const currentDir = path.dirname(fileURLToPath(import.meta.url));
  const patchesListPath = path.resolve(
    currentDir,
    '../../../patches-list.json',
  );
  const bundleListPath = path.resolve(
    currentDir,
    '../../../patches-bundle.json',
  );
  const changelogPath = path.resolve(currentDir, '../../../CHANGELOG.md');

  const rawList: RawPatchesList = JSON.parse(
    fs.readFileSync(patchesListPath, 'utf-8'),
  );
  const rawBundle: RawBundle | null = fs.existsSync(bundleListPath)
    ? JSON.parse(fs.readFileSync(bundleListPath, 'utf-8'))
    : null;
  const changelogContent: string | null = fs.existsSync(changelogPath)
    ? fs.readFileSync(changelogPath, 'utf-8')
    : null;

  return { rawList, rawBundle, changelogContent };
}

function assembleRepositoryData(
  rawList: RawPatchesList,
  entities: RepositoryEntities,
  release: ReleaseInfo,
) {
  const { apps, patches, versionStatuses } = entities;

  for (const item of release.recentChanges) {
    const matchedApp = resolveAppForScope(item.scope, apps);
    if (matchedApp) {
      item.appId = matchedApp.id;
      item.appName = matchedApp.name;
      item.appPackageName = matchedApp.packageName;
    }
  }

  const stats: RepositoryStats = {
    supportedAppsCount: apps.length,
    totalPatchesCount: patches.length,
    bundleVersion: release.version || rawList.version,
    releaseDate: release.releaseDate,
  };

  return {
    apps,
    patches,
    stats,
    release,
    versionStatuses,
  };
}

async function initRepositoryData() {
  const { rawList, rawBundle, changelogContent } = readLocalFiles();
  const entities = buildRepositoryEntities(rawList);
  const release = await resolveLatestRelease({
    bundleJson: rawBundle,
    changelogContent,
  });
  return assembleRepositoryData(rawList, entities, release);
}

function initRepositoryDataSync() {
  const { rawList, rawBundle, changelogContent } = readLocalFiles();
  const entities = buildRepositoryEntities(rawList);
  const release = resolveLatestReleaseSync({
    bundleJson: rawBundle,
    changelogContent,
  });
  return assembleRepositoryData(rawList, entities, release);
}

// Static builds intentionally attempt to resolve current release metadata from
// GitHub via initRepositoryData. If GitHub is unavailable or rate-limited, the lookup
// is bounded by a 5-second timeout in fetchLatestGitHubRelease before falling back
// synchronously to local bundle and changelog files via initRepositoryDataSync.
try {
  cachedData = await initRepositoryData();
} catch {
  cachedData = initRepositoryDataSync();
}

export function loadRepositoryData() {
  if (!cachedData) {
    cachedData = initRepositoryDataSync();
  }
  return cachedData;
}
export function getApps(): App[] {
  return loadRepositoryData().apps;
}

export function getPatches(): Patch[] {
  return loadRepositoryData().patches;
}

export function getPatchesForApp(appId: string): Patch[] {
  return loadRepositoryData().patches.filter((p) =>
    p.compatibleAppIds.includes(appId),
  );
}

export function getRepositoryStats(): RepositoryStats {
  return loadRepositoryData().stats;
}

export function getLatestRelease(): ReleaseInfo {
  return loadRepositoryData().release;
}

export function getChangelogContent(): string {
  const { changelogContent } = readLocalFiles();
  return changelogContent || '';
}

export function getInitialVersionStatuses(): AppVersionStatus[] {
  return loadRepositoryData().versionStatuses;
}

export function getLatestPlayRelease(): AppVersionStatus | null {
  const statuses = getInitialVersionStatuses();
  let latest: AppVersionStatus | null = null;
  let latestTime = Number.NEGATIVE_INFINITY;
  for (const status of statuses) {
    if (!status.updatedAt) continue;

    const timestamp = new Date(status.updatedAt).getTime();
    if (Number.isNaN(timestamp) || timestamp <= latestTime) continue;

    latestTime = timestamp;
    latest = status;
  }
  return latest;
}
